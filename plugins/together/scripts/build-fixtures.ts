// Regenerate with: bun scripts/build-fixtures.ts (from together/)
// The test kit runs with no fs, so fixtures ship as a generated module.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = join(import.meta.dir, '..')
const fixtures = join(root, 'tests/fixtures')
const lists = Object.fromEntries(
  readdirSync(fixtures)
    .filter(name => name.endsWith('.md'))
    .sort()
    .map(name => [name.replace(/\.md$/, ''), readFileSync(join(fixtures, name), 'utf8')]),
)
const format = readFileSync(join(root, 'skills/list/SKILL.md'), 'utf8')
const example = /```list\n([\s\S]*?)```/.exec(format)?.[1]
if (example === undefined) throw new Error('SKILL.md has no ```list example block')
writeFileSync(
  join(fixtures, 'fixtures.gen.ts'),
  `// Generated by scripts/build-fixtures.ts — do not edit.\nexport const LISTS: Record<string, string> = ${JSON.stringify(lists, null, 2)}\n\nexport const FORMAT_EXAMPLE = ${JSON.stringify(example)}\n`,
)
